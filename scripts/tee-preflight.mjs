// FREE TEE preflight for the swarm2 proposer models. No model call, no completion, no signing, no transaction.
// Per proposer model it fetches NEAR AI's public attestation report (unauthenticated GET /v1/attestation/report with a
// fresh nonce, exactly as runtime/agents/tee-client.mjs does before a paid call), verifies each Intel TDX quote with
// @phala/dcap-qvl against public PCCS collateral, and prints the observed mrTd:mrConfigId and whether it is already in
// the reviewed policy. Each GPU payload is verified by NVIDIA NRAS against the freshly fetched JWKS keys.
// Attestation fetches are not model calls and cost nothing.
//
//   node scripts/tee-preflight.mjs [--policy docs/tee-policy.json] [--write-candidate]
//
// --write-candidate writes docs/tee-policy.candidate.json (schemaVersion 0, NOT a runnable policy) with entries for the
// models whose measurements are missing and NVIDIA NRAS keys refreshed from the fixed JWKS URL. A human reviews it and
// copies accepted values into docs/tee-policy.json; nothing here edits the real policy.
//
// NEARAI_API_KEY is read from the environment ONLY if the public endpoint answers 401/403, and is never printed.
import { randomBytes } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { hex, inspectReport, verifyGpuToken } from '../runtime/agents/tee.mjs';
import { SWARM2_PROPOSERS } from '../runtime/agents/swarm-config.mjs';

const REPORT_URL = 'https://cloud-api.near.ai/v1/attestation/report';
const JWKS_URL = 'https://nras.attestation.nvidia.com/.well-known/jwks.json';
const NRAS_URL = 'https://nras.attestation.nvidia.com/v3/attest/gpu'; // same fixed verifier tee-client.mjs uses
const MEASUREMENT = /^[a-f0-9]{96}:[a-f0-9]{96}$/;
// mrTd values recomputed from the public dstack v0.5.12 release (docs/TEE-VERIFICATION.md, "Trust-policy decision").
export const REPRODUCED_MRTD = Object.freeze({
  '7fe60787222bd394cb516abca2435f22f035ab2cc9c0a4b4b3b148e46297f3d931a237b72f359052c6e657d8c1409173': 'dstack v0.5.12 ovmf.fd, two-pass TDVF (QEMU 8.2.2): gateway image',
  df4d77c857de652bd0fafa343a2026b51071ee03773d076d283abf1a7d36ff91ffa279ee4a617ac664f7e2a2c8d5891b: 'dstack v0.5.12 ovmf.fd, single-pass TDVF (QEMU 9.2.1): dstack-nvidia model image',
});
const CHECKS = ['tdxQuoteVerified', 'nonceBound', 'configurationBound', 'eventLogVerified'];

/** Public P-384 keys only (kty, crv, kid, x, y); certificate chains and anything private are dropped. */
export function nrasKeysFromJwks(jwks) {
  const keys = (Array.isArray(jwks?.keys) ? jwks.keys : []).filter(k => k?.kty === 'EC' && k.crv === 'P-384' && typeof k.kid === 'string' && typeof k.x === 'string' && typeof k.y === 'string' && !Object.hasOwn(k, 'd'))
    .map(({ kty, crv, kid, x, y }) => ({ kty, crv, kid, x, y }));
  if (keys.length < 1 || keys.length > 1024 || new Set(keys.map(k => k.kid)).size !== keys.length) throw new Error('NRAS JWKS has no usable distinct P-384 keys');
  return keys;
}

function osImageHash(eventLog) {
  try {
    const events = typeof eventLog === 'string' ? JSON.parse(eventLog) : eventLog;
    const hit = events.find(e => e?.imr === 3 && e.event === 'os-image-hash');
    return typeof hit?.event_payload === 'string' ? hit.event_payload.toLowerCase() : null;
  } catch { return null; }
}

/** One quote-bearing report -> its observed measurement and the local checks (pure, given a dcap result). */
export function summarizeReport(report, quoteResult, { nonce, allowed }) {
  const flags = inspectReport(report, quoteResult, { nonce, allowedMeasurements: allowed });
  const td = quoteResult?.report?.asTd10?.();
  const mrTd = td ? Buffer.from(td.mrTd).toString('hex') : null;
  const measurement = td ? `${mrTd}:${Buffer.from(td.mrConfigId).toString('hex')}` : null;
  return { measurement, inPolicy: flags.measurementPolicyMatched === true, mrTdReproduced: REPRODUCED_MRTD[mrTd] ?? null,
    osImageHash: osImageHash(report.event_log), checks: Object.fromEntries(CHECKS.map(k => [k, flags[k] === true])) };
}

/** Candidate file: only models with a fully checked measurement that the policy lacks. Never a runnable policy. */
export function buildCandidate(policy, results, nrasKeys, observedAt) {
  const usable = r => r.instances.length > 0 && r.instances.every(i => MEASUREMENT.test(i.measurement ?? '') && CHECKS.every(k => i.checks[k]) && i.gpuAttested);
  const missing = results.filter(r => usable(r) && r.instances.some(i => !i.inPolicy));
  const add = (list, values) => [...new Set([...list, ...values])];
  return {
    schemaVersion: 0, reviewRequired: true, observedAt,
    note: 'PUBLIC REVIEW CANDIDATE, not an accepted policy. Generated by scripts/tee-preflight.mjs from unauthenticated attestation reports (no model call). DCAP quote, nonce, compose/mrConfigId, RTMR3 event log and NVIDIA NRAS GPU token (nonce + ES384 against the JWKS below) checked. Review before copying values into docs/tee-policy.json.',
    entries: missing.map(r => ({ model: r.model, measurements: [...new Set(r.instances.map(i => i.measurement))], mrTdReproduced: [...new Set(r.instances.map(i => i.mrTdReproduced))], osImageHash: [...new Set(r.instances.map(i => i.osImageHash))] })),
    unattested: results.filter(r => !usable(r)).map(r => ({ model: r.model, error: r.error ?? 'checks failed' })),
    proposedPolicy: { ...policy,
      gatewayMeasurements: add(policy.gatewayMeasurements, results.filter(usable).map(r => r.gateway?.measurement).filter(m => MEASUREMENT.test(m ?? ''))),
      modelMeasurements: add(policy.modelMeasurements, missing.flatMap(r => r.instances.map(i => i.measurement))),
      nrasKeys },
  };
}

export async function fetchCapped(url, { headers = {}, cap = 4 * 1024 * 1024, method = 'GET', body } = {}) {
  const response = await fetch(url, { method, body, headers: { Accept: 'application/json', 'Accept-Encoding': 'identity', ...(body ? { 'Content-Type': 'application/json' } : {}), ...headers }, redirect: 'error', signal: AbortSignal.timeout(60000) });
  const text = await response.text();
  if (text.length > cap) throw new Error('response too large');
  return { status: response.status, text };
}

async function attestationReport(model, nonce) {
  const url = `${REPORT_URL}?${new URLSearchParams({ model, provider: 'near', include_tls_fingerprint: 'false', signing_algo: 'ecdsa', nonce })}`;
  let { status, text } = await fetchCapped(url);
  if ((status === 401 || status === 403) && process.env.NEARAI_API_KEY) ({ status, text } = await fetchCapped(url, { headers: { Authorization: `Bearer ${process.env.NEARAI_API_KEY}` } }));
  let body = null; try { body = JSON.parse(text); } catch { /* reported below */ }
  if (status !== 200) throw new Error(`HTTP ${status}: ${String(body?.error?.message ?? 'no attestation').slice(0, 160)}`);
  return body;
}

export async function checkModel(model, policy, dcap, now, nrasKeys) {
  const nonce = randomBytes(32).toString('hex');
  try {
    const report = await attestationReport(model, nonce);
    const models = report?.model_attestations;
    if (!report?.gateway_attestation || !Array.isArray(models) || models.length < 1 || models.length > 16) throw new Error('no gateway + model attestation in the report');
    const verify = async (r, allowed) => {
      const quote = hex(r.intel_quote);
      const collateral = await dcap.getCollateral(dcap.PHALA_PCCS_URL, quote);
      return summarizeReport(r, await dcap.verify(quote, collateral, now), { nonce, allowed });
    };
    const gateway = await verify(report.gateway_attestation, policy.gatewayMeasurements);
    const instances = [];
    for (const r of models) {
      if (r?.model_name !== model) throw new Error('report names a different model');
      let gpu = null; try { gpu = JSON.parse(r.nvidia_payload); } catch { /* gpu evidence missing */ }
      let gpuAttested = false;
      if (gpu?.nonce?.toLowerCase() === nonce) {
        const nras = await fetchCapped(NRAS_URL, { method: 'POST', body: JSON.stringify(gpu) });
        let token = null; try { const parsed = JSON.parse(nras.text); token = parsed?.[0]?.[0] === 'JWT' ? parsed[0][1] : null; } catch { /* rejected below */ }
        gpuAttested = nras.status === 200 && typeof token === 'string' && verifyGpuToken(token, nonce, nrasKeys, Math.floor(Date.now() / 1000));
      }
      instances.push({ ...(await verify(r, policy.modelMeasurements)), gpuAttested });
    }
    return { model, gateway, instances };
  } catch (error) {
    return { model, error: String(error?.message ?? error).replace(/Bearer\s+\S+/g, 'Bearer [redacted]').slice(0, 200), gateway: null, instances: [] };
  }
}

async function main() {
  const { values } = parseArgs({ options: { policy: { type: 'string', default: 'docs/tee-policy.json' }, 'write-candidate': { type: 'boolean', default: false } } });
  const policy = JSON.parse(await readFile(values.policy, 'utf8'));
  const dcap = (await import('@phala/dcap-qvl')).default;
  const now = Math.floor(Date.now() / 1000);
  const observedAt = new Date(now * 1000).toISOString();
  const jwks = JSON.parse((await fetchCapped(JWKS_URL)).text);
  const nrasKeys = nrasKeysFromJwks(jwks);
  const results = [];
  for (const { name, model } of SWARM2_PROPOSERS) {
    const result = await checkModel(model, policy, dcap, now, nrasKeys);
    results.push(result);
    if (result.error) { console.log(`${name.padEnd(13)} ${model}\n  NO ATTESTATION: ${result.error}`); continue; }
    console.log(`${name.padEnd(13)} ${model}\n  gateway ${result.gateway.measurement} ${result.gateway.inPolicy ? 'IN POLICY' : 'NOT IN POLICY'}`);
    for (const i of result.instances) {
      const failed = CHECKS.filter(k => !i.checks[k]).concat(i.gpuAttested ? [] : ['gpuAttested']);
      console.log(`  model   ${i.measurement} ${i.inPolicy ? 'IN POLICY' : 'NOT IN POLICY'}\n          mrTd: ${i.mrTdReproduced ?? 'not reproduced'}; os-image-hash ${i.osImageHash ?? 'missing'}; checks ${failed.length ? `FAILED ${failed.join(',')}` : 'all passed'}`);
    }
  }
  const kids = new Set(policy.nrasKeys.map(k => k.kid));
  console.log(`NRAS JWKS: ${nrasKeys.length} P-384 keys, ${nrasKeys.filter(k => !kids.has(k.kid)).length} not in the policy, ${policy.nrasKeys.filter(k => !nrasKeys.some(n => n.kid === k.kid)).length} policy keys no longer published`);
  const candidate = buildCandidate(policy, results, nrasKeys, observedAt);
  console.log(`Missing from policy: ${candidate.entries.map(e => e.model).join(', ') || 'none'}; no attestation: ${candidate.unattested.map(e => e.model).join(', ') || 'none'}`);
  if (values['write-candidate']) {
    await writeFile('docs/tee-policy.candidate.json', `${JSON.stringify(candidate, null, 2)}\n`);
    console.log('Wrote docs/tee-policy.candidate.json (schemaVersion 0, review required).');
  }
  if (candidate.unattested.length) process.exitCode = 1;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
